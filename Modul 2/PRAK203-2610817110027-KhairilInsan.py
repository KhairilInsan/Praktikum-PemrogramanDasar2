a = float(input("Masukkan Nilai Pertama: "))
b = float(input("Masukkan Nilai Kedua: "))
i = float(input("Masukkan Nilai Ketiga: "))
j = float(input("Masukkan Nilai Keempat: "))
x = float(input("Masukkan Nilai Kelima: "))
y = float(input("Masukkan Nilai Keenam: "))

total = (a - b) * i / j - (x + y)

print(f"{total:.3f}")
